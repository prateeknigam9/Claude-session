# Splits the script section into sentences and plans each at 3.4 words/s + pauses (0.25 inside a paragraph, 0.4 between).
import re, sys, json
src = open('script.md', encoding='utf8').read()
a, b, out = sys.argv[1], sys.argv[2], sys.argv[3]; t = float(sys.argv[4]) if len(sys.argv) > 4 else 0.6
sec = src.split(a, 1)[1].split(b, 1)[0]
rows = []
for l in sec.split('\n')[1:]:
    l = l.strip()
    if not l or l[0] in '-#|[' : continue
    l2 = re.sub(r'((?:[A-Z]\.){2,})', lambda m: m.group(1).replace('.', '§'), l)
    l2 = re.sub(r'(?<![A-Za-z])([A-Z])\.(?= [A-Z][a-z])', lambda m: m.group(1) + '§', l2)   # single initials: John J. Ray
    raw = [s.strip().replace('§', '.') for s in re.findall(r'[^.?!…]+(?:[.?!…]+["”]?|$)', l2) if s.strip()]
    sents = []
    for s in raw:   # merge very short sentences so the band reads as phrases
        if sents and (len(sents[-1].split()) < 5 or len(s.split()) < 3) and len(sents[-1].split()) + len(s.split()) <= 14: sents[-1] += ' ' + s
        else: sents.append(s)
    for i, s in enumerate(sents):
        d = len(s.split()) / 3.4; rows.append([round(t, 2), round(t + d, 2), s]); t += d + (0.25 if i < len(sents) - 1 else 0.4)
open(out, 'w', encoding='utf8').write('// generated by tools/plan_timing.py from script.md (planned at 3.4 words/s)\nvoTrack(' + json.dumps(rows, ensure_ascii=False, indent=0) + ');\n')
for r in rows: print(f'{r[0]:6.1f} {r[1]:6.1f}  {r[2]}')
print('END', round(t, 1))
