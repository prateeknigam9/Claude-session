# plan.py <start-marker> <end-marker> <part-dir> [t0] [script]  — style-v2 planner (Case 04: script-v1.md). A part-dir without partN writes vo_open.js
# Each narration line in the script = one voice line. "(low|warm|build|hit|title)" sets the mood (carries on until changed),
# "[pause]" (alone or at a line end) adds a held pause, a blank line between paragraphs adds a breath.
# Writes <part-dir>/src/vo_partN.js (planned band for the storyboard) and <part-dir>/vo/LINES.tsv (id, text, gap, mood)
# for make_chatterbox.py. Planned pace ≈ Chatterbox's measured pace (≈ 2.75 words/s while speaking).
import re, sys, os, json
a, b, d = sys.argv[1], sys.argv[2], sys.argv[3]; t = float(sys.argv[4]) if len(sys.argv) > 4 else 0.6
src = open(sys.argv[5] if len(sys.argv) > 5 else "script-v1.md", encoding="utf8").read(); sec = src.split(a, 1)[1].split(b, 1)[0].split('\n')[1:]
RATE = {'low': 2.6, 'warm': 2.75, 'build': 2.95, 'hit': 2.2, 'title': 2.6}
rows, mood, para_break = [], 'low', False
for raw in sec:
    l = raw.strip()
    if not l: para_break = True; continue
    if l.startswith(('[SCREEN', '#', '-', '|', '`')): continue
    if l.startswith('[pause'):
        if rows: rows[-1][3] += 1.5 if '1.5' in l else 1.2
        continue
    m = re.match(r'\((low|warm|build|hit|title)\)\s*', l)
    if m: mood = m.group(1); l = l[m.end():]
    hold = 0
    if l.endswith('[pause]'): l = l[:-7].strip(); hold = 1.2
    if rows and para_break: rows[-1][3] = max(rows[-1][3], .6)
    para_break = False
    rows.append([l, mood, len(l.split()) / RATE[mood], .35 + hold])
os.makedirs(f'{d}/src', exist_ok=True); os.makedirs(f'{d}/vo', exist_ok=True)
band, lines = [], ['id\ttext\tgap\tmood']
for i, (txt, md, dur, gap) in enumerate(rows):
    band.append([round(t, 2), round(t + dur, 2), txt]); lines.append(f'{i + 1:02d}\t{txt}\t{round(gap, 2)}\t{md}'); t += dur + gap
m = re.search(r'part(\d)', d); N = m.group(1) if m else None
open(f'{d}/src/vo_part{N}.js' if N else f'{d}/src/vo_open.js', 'w', encoding='utf8').write('// generated by tools/plan_v2.py from script-v2.md\nvoTrack(' + json.dumps(band, ensure_ascii=False, indent=0) + ');\n')
open(f'{d}/vo/LINES.tsv', 'w', encoding='utf8').write('\n'.join(lines) + '\n')
for (s, e, x), (_, md, _, g) in zip(band, rows): print(f'{s:6.1f} {e:6.1f} {md:5} {g:4.2f}  {x}')
print('END', round(t, 1))
